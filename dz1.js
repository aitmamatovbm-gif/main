function div(x, y){
    if (y === 0){
        console.log("Ошибка: на ноль делить нельзя!");
        return null;
    }  
    return x / y;
}

function mul(x, y){
    return x * y;
}

function add(x, y){
    return x + y;
}

function sub(x, y){
    return x - y;
}

let num1 = 15;
let num2 = 10; 

let oper = "/";

if (oper === "/"){
    console.log(div(num1, num2));
} else if (oper === "*"){
    console.log(mul(num1, num2));
} else if (oper === "+"){
   console.log(add(num1, num2));
} else if (oper === "-"){
    console.log(sub(num1, num2)); 
} else {
    console.log("Неизвестная операция");
}

/*
Объяснение простыми словами:

Представь, что эта программа — маленький калькулятор.

Сначала она знает четыре способа считать:
- div делит одно число на другое;
- mul умножает числа;
- add складывает числа;
- sub вычитает второе число из первого.

Числа для примера лежат в коробочках num1 и num2.
Сейчас в первой коробочке лежит 15, а во второй — 10.

В коробочке oper лежит знак действия. Сейчас это знак деления "/".
Программа смотрит на этот знак и выбирает нужный способ подсчёта.
Так как знак — "/", она делит 15 на 10 и показывает ответ на экране.

Если выбрать деление на ноль, программа покажет сообщение об ошибке,
потому что на ноль делить нельзя.
Если выбрать незнакомый знак, программа сообщит, что операция неизвестна.
*/
